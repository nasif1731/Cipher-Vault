def sub_bytes(state):
    for r in range(4):
        for c in range(4):
            b = state[r][c]
            state[r][c] = SBOX[b >> 4][b & 0x0F]

def shift_rows(state):
    # Left shifts: 0, 1, 2, 3 places
    state[1] = state[1][1:] + state[1][:1]
    state[2] = state[2][2:] + state[2][:2]
    state[3] = state[3][3:] + state[3][:3]

def mix_columns(state):
    for c in range(4):
        t0, t1, t2, t3 = state[0][c], state[1][c], state[2][c], state[3][c]
        state[0][c] = general_mul(t0, 2) ^ general_mul(t1, 3) ^ t2      ^ t3
        state[1][c] = t0      ^ general_mul(t1, 2) ^ general_mul(t2, 3) ^ t3
        state[2][c] = t0      ^ t1      ^ general_mul(t2, 2) ^ general_mul(t3, 3)
        state[3][c] = general_mul(t0, 3) ^ t1      ^ t2      ^ general_mul(t3, 2)
        
def add_round_key(state, key):
    for r in range(4):
        for c in range(4):
            state[r][c] ^= key[r][c]
            
def inv_sub_bytes(state):
    for r in range(4):
        for c in range(4):
            b = state[r][c]
            state[r][c] = INV_SBOX[b >> 4][b & 0x0F]

def inv_shift_rows(state):
    # Right shifts: 0, 1, 2, 3 places
    state[1] = state[1][-1:] + state[1][:-1]
    state[2] = state[2][-2:] + state[2][:-2]
    state[3] = state[3][-3:] + state[3][:-3]

