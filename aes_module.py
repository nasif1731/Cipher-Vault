def aes_encrypt(plaintext_bytes, key_bytes):
    """Performs AES-128 encryption on a single 16-byte block."""
    state = bytes_to_matrix(plaintext_bytes)
    round_keys = expand_key(key_bytes)

    add_round_key(state, round_keys[0])

    for r in range(1, 10):
        sub_bytes(state)
        shift_rows(state)
        mix_columns(state)
        add_round_key(state, round_keys[r])

    sub_bytes(state)
    shift_rows(state)
    add_round_key(state, round_keys[10])

    return matrix_to_bytes(state)

def aes_decrypt(ciphertext_bytes, key_bytes):
    """Performs AES-128 decryption on a single 16-byte block."""
    state = bytes_to_matrix(ciphertext_bytes)
    round_keys = expand_key(key_bytes)

    # 1. Final Round Inverse (R10)
    add_round_key(state, round_keys[10])
    inv_shift_rows(state)
    inv_sub_bytes(state)

    # 2. Middle Rounds Inverse (R9 down to R1)
    for r in range(9, 0, -1):
        add_round_key(state, round_keys[r])
        inv_mix_columns(state)
        inv_shift_rows(state)
        inv_sub_bytes(state)

    # 3. Final Step (R0)
    add_round_key(state, round_keys[0])

    return matrix_to_bytes(state)


