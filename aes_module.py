# =========================================
# MATRIX & HELPER FUNCTIONS
# =========================================

def bytes_to_matrix(b):
    """Converts 16 bytes into a 4x4 state matrix (Row-Major)."""
    return [list(b[i:i+4]) for i in range(0, 16, 4)]

def matrix_to_bytes(m):
    return bytes(sum(m, []))

def matrix_to_hex(m):
    return ''.join(f"{b:02X}" for row in m for b in row)

# =========================================
# KEY EXPANSION
# =========================================

def expand_key(master_key):
    """Generates 11 round keys (K0 to K10) for AES-128."""
    key_columns = [list(master_key[i:i+4]) for i in range(0, 16, 4)]
    columns = deepcopy(key_columns)
    i = 4

    while len(columns) < 44:
        word = columns[-1].copy()
        if i % 4 == 0:
            word = word[1:] + word[:1]
            word = [SBOX[b >> 4][b & 0x0F] for b in word]
            word[0] ^= RCON[i // 4]
        word = [x ^ y for x, y in zip(word, columns[-4])]
        columns.append(word)
        i += 1

    round_keys = []
    for r in range(11):
        block = columns[4*r : 4*(r+1)]
        
        # This aligns the four 4-byte column words into the 4x4 row-major key matrix.
        key_matrix = [
            [block[0][i], block[1][i], block[2][i], block[3][i]] 
            for i in range(4) # i iterates over rows (0 to 3)
        ]
        round_keys.append(key_matrix)
    return round_keys

# =========================================
# GALOIS FIELD ARITHMETIC (Fixed)
# =========================================

def general_mul(a, b):
    """General Galois Field multiplication (Fixed and Verified)."""
    p = 0
    while b > 0:
        if b & 1: 
            p ^= a
            
        a_hi = a & 0x80
        a = (a << 1)
        if a_hi: 
            a ^= 0x1B
            
        a &= 0xFF
        b >>= 1
    return p

